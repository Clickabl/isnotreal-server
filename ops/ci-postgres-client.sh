#!/usr/bin/env bash
# CI only: put PostgreSQL client tools of the CI server's major version first on PATH.
# pg_dump output restores only into the same or a newer server, so the PostgreSQL 10 job
# must back up and restore with PostgreSQL 10 tools, as the production cPanel host does.
#
#   bash ops/ci-postgres-client.sh 17
set -euo pipefail
major="${1:?Usage: bash ops/ci-postgres-client.sh <server major version>}"
[[ "$major" =~ ^[0-9]+$ ]] || { echo "invalid PostgreSQL major version: $major" >&2; exit 2; }
: "${GITHUB_PATH:?This script is for CI only}"

if ((major >= 13)); then
  if [[ ! -x "/usr/lib/postgresql/$major/bin/pg_dump" ]]; then
    source /etc/os-release
    sudo install -d /usr/share/postgresql-common/pgdg
    sudo curl --fail --silent --show-error https://www.postgresql.org/media/keys/ACCC4CF8.asc \
      -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.asc
    printf 'deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc] https://apt.postgresql.org/pub/repos/apt %s-pgdg main\n' "$VERSION_CODENAME" \
      | sudo tee /etc/apt/sources.list.d/isnotreal-pgdg.list >/dev/null
    sudo apt-get update -qq
    sudo apt-get install -y "postgresql-client-$major"
  fi
  printf '%s\n' "/usr/lib/postgresql/$major/bin" >>"$GITHUB_PATH"
  exit 0
fi

# PGDG no longer packages end-of-life majors for current Ubuntu, so run the official
# server image's own tools against the job's PostgreSQL service on the host network.
image="postgres:$major-alpine"
bin="${RUNNER_TEMP:?}/postgresql-$major-client"
mkdir -p "$bin"
for tool in psql pg_dump pg_restore; do
  cat >"$bin/$tool" <<EOF
#!/usr/bin/env bash
# Generated by ops/ci-postgres-client.sh: run $tool $major from $image.
# libpq settings (PG*) and the bootstrap's ISNOTREAL_* secrets pass through by name only.
set -euo pipefail
pass=()
while IFS= read -r name; do pass+=(-e "\$name"); done < <(compgen -e | grep -E '^(PG|ISNOTREAL_)' || true)
exec docker run --rm -i --network host -e HOME=/tmp "\${pass[@]}" \\
  -v "\$PWD:\$PWD" -v /tmp:/tmp -w "\$PWD" $image $tool "\$@"
EOF
  chmod +x "$bin/$tool"
done
docker pull --quiet "$image" >/dev/null
"$bin/pg_dump" --version
printf '%s\n' "$bin" >>"$GITHUB_PATH"
